import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/opt/hermes/tools/chromium-1208/chrome-linux64/chrome', headless: true, args: ['--no-sandbox'] });
const framework = process.env.DEMO || 'react';
const page = await browser.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(process.env.DEMO_URL || 'http://127.0.0.1:5291');
  await page.getByTestId('grab-guide').waitFor();
  if (framework === 'react') {
    const post = page.getByTestId('post').first();
    await post.getByRole('button', { name: 'Like post' }).click();
    assert.equal(await post.getByRole('button', { name: 'Like post' }).getAttribute('aria-pressed'), 'true');
    await post.getByRole('button', { name: 'Reply to post' }).click();
    await post.getByRole('textbox').fill('A real reply');
    await post.getByRole('button', { name: 'Reply', exact: true }).click();
    await post.locator('.posted-reply').filter({ hasText: 'A real reply' }).waitFor();
    await page.getByRole('button', { name: 'Saved only' }).click();
    await page.getByText('No posts in this view.').waitFor();
    await page.getByRole('button', { name: 'For you', exact: true }).click();
    assert.equal(await post.getByRole('button', { name: 'Like post' }).getAttribute('aria-pressed'), 'true', 'filtering preserves likes');
    await post.locator('.posted-reply').filter({ hasText: 'A real reply' }).waitFor();
    await post.getByRole('button', { name: 'Repost', exact: true }).click();
    assert.equal(await post.getByRole('button', { name: 'Repost', exact: true }).getAttribute('aria-pressed'), 'true');
    await post.getByRole('button', { name: 'Save post', exact: true }).click();
    await page.getByRole('button', { name: 'Saved only' }).click();
    assert.equal(await page.locator('[data-testid="post"]:visible').count(), 1);
    await page.getByRole('button', { name: 'For you', exact: true }).click();
  } else if (framework === 'vue') {
    await page.getByRole('button', { name: 'Add to Cart' }).click();
    await page.getByRole('alert').filter({ hasText: 'Choose a color and size' }).waitFor();
    await page.getByRole('button', { name: 'Forest', exact: true }).click();
    await page.getByRole('button', { name: 'M', exact: true }).click();
    await page.getByRole('button', { name: 'Add to Cart' }).click();
    await page.getByTestId('cart-total').filter({ hasText: '$68.00' }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Close cart' }).evaluate(el => el === document.activeElement), true, 'cart receives keyboard focus');
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.getByRole('button', { name: 'Review demo bag' }).evaluate(el => el === document.activeElement), true, 'cart traps reverse Tab');
    await page.getByRole('button', { name: 'Review demo bag' }).click();
    await page.getByText('Demo bag reviewed. No payment or order was submitted.').waitFor();
    await page.getByRole('button', { name: 'Remove Novo Crewneck' }).click();
    await page.getByText('Your cart is empty.').waitFor();
    await page.getByRole('button', { name: 'Close cart' }).click();
  } else {
    await page.getByRole('button', { name: '+ New Note' }).click();
    await page.getByRole('textbox', { name: 'Note title', exact: true }).fill('Browser-tested note');
    await page.getByRole('textbox', { name: 'Note body', exact: true }).fill('three useful words');
    await page.getByText('3 words', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Format ↓' }).click();
    await page.getByRole('button', { name: 'Bold', exact: true }).click();
    assert.match(await page.getByRole('textbox', { name: 'Note body', exact: true }).inputValue(), /\*\*/);
    await page.getByRole('searchbox', { name: 'Search notes' }).fill('no-such-note');
    await page.getByText('No matching notes.').waitFor();
    await page.getByRole('searchbox', { name: 'Search notes' }).fill('');
    await page.getByTestId('note-card').filter({ hasText: 'Weekend reading' }).click();
    await page.getByTestId('note-card').filter({ hasText: 'Browser-tested note' }).click();
    assert.match(await page.getByRole('textbox', { name: 'Note body', exact: true }).inputValue(), /\*\*/);
  }
  await page.getByTestId('freeze-trigger').focus();
  await page.getByTestId('freeze-popover').waitFor({ state: 'visible' });
  const motion = page.getByTestId('motion-sample');
  assert.notEqual(await motion.evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.keyboard.down('Control');
  await page.keyboard.down('c');
  await page.locator('[data-point-grab-btn="freeze"]').waitFor();
  await page.keyboard.up('c');
  await page.keyboard.up('Control');
  await page.getByTestId('freeze-trigger').hover();
  await page.keyboard.press('f');
  await page.locator('#__point-grab-freeze-anim-styles__').waitFor({ state: 'attached' });
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const paused = await motion.evaluate(el => ({ playState: getComputedStyle(el).animationPlayState, transform: getComputedStyle(el).transform }));
  assert.equal(paused.playState, 'paused');
  await page.mouse.move(5, 5);
  await page.waitForTimeout(160);
  assert.equal(await motion.evaluate(el => getComputedStyle(el).transform), paused.transform);
  await page.getByTestId('freeze-popover').waitFor({ state: 'visible' });
  await page.keyboard.press('Escape');
  await page.locator('#__point-grab-freeze-anim-styles__').waitFor({ state: 'detached' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await motion.evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'mobile horizontal overflow');
  assert.deepEqual(errors, []);
  console.log(`${framework}: state, accessible popover, motion, reduced-motion, mobile overflow PASS`);
} finally { await browser.close(); }
